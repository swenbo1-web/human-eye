"""Reuse the accepted held-process bridge and preserve this task's own limits."""

import hashlib
import json
from pathlib import Path
import shutil

HERE=Path(__file__).resolve().parent
PRIOR=HERE.with_name('m4_cross_scale_discovery_001')


def main():
    (HERE/'harness/reused').mkdir(parents=True,exist_ok=True)
    (HERE/'public_schema').mkdir(exist_ok=True)
    records=[]
    names=['harness/budget.py','harness/mcp_entry.py','harness/owned_runtime.py','harness/state_owned_native.py',
           'harness/reused/owned_native.py','harness/reused/process_proof.py','harness/reused/stdio_checks.py',
           'harness/reused/verified_bootstrap.py','harness/reused/wire_meter.py','SHARED_DEPENDENCY.json']
    for name in names:
        source=PRIOR/name
        original=source.read_bytes()
        text=original.decode('utf8')
        if name.endswith('budget.py'):
            text=text.replace('"all_rasters": 64','"all_rasters": 24')
        if name.endswith('owned_runtime.py'):
            text=text.replace('D:/he_m4_cross_scale_001','D:/he_m4_m5_source_region_001')
            text=text.replace("ASSET = Path('D:/he_m4_global_local_001/fixture/main.blend')","ASSET = EXTERNAL / 'fixture/main.blend'")
            text=text.replace("ASSET_SHA256 = 'a2d55e9212a84d27489aa72a680092b4e91d94d9df27d29c5de40d8a4ca3d0c6'",
                              "ASSET_SHA256 = json.loads((NAMESPACE/'fixture/ASSET_BINDING.json').read_bytes())['asset_sha256']")
            text=text.replace('len(self.binding["source_manifest"]) != 142','len(self.binding["source_manifest"]) < 143')
        if name.endswith('mcp_entry.py'):
            text=text.replace('event != "active_observation_render_attempt"',
                'event not in ("active_observation_render_attempt", "source_region_render_attempt")')
            text=text.replace('event.get("event")=="active_observation_render_attempt"',
                'event.get("event") in ("active_observation_render_attempt", "source_region_render_attempt")')
        if name.endswith('owned_native.py'):
            # Each Blender worker imports its own harness wire meter. Its source
            # is retained directly and needs no generated bytecode artifact.
            text=text.replace('MAX_CODE=256*1024;', 'sys.dont_write_bytecode=True\n\nMAX_CODE=256*1024;')
        target=HERE/name
        target.write_text(text,encoding='utf8',newline='\n')
        records.append(dict(original=str(source),original_sha256=hashlib.sha256(original).hexdigest(),
                            target=name,target_sha256=hashlib.sha256(target.read_bytes()).hexdigest()))
    # Asset and state-target binding are filled once after successful fixture construction.
    with (HERE/'HARNESS_MIGRATION_INITIAL.json').open('x',encoding='utf8',newline='\n') as stream:
        json.dump(dict(records=records,new_actual_operations=0),stream,sort_keys=True,indent=2)
        stream.write('\n')
    print(json.dumps(dict(migrated=len(records),live=0)))


if __name__=='__main__':
    main()
