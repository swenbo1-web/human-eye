def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return json.loads(Path(path).read_bytes())


def save(path, value):
    with Path(path).open('x', encoding='utf8', newline='\n') as stream:
        json.dump(value, stream, sort_keys=True, indent=2, ensure_ascii=False, allow_nan=False)
        stream.write('\n')
        stream.flush()
        os.fsync(stream.fileno())


def inventory(directory):
    paths = []
    for current, directories, names in os.walk(directory, followlinks=False):
        for name in directories + names:
            path = Path(current) / name
            if path.is_symlink() or path.is_junction():
                raise ValueError('reparse_entry/' + str(path))
            path.resolve().relative_to(directory.resolve())
        paths.extend(Path(current) / name for name in names)
    return sorted(paths)


def clean_generated_bytecode():
    rows = []
    for path in sorted(HERE.rglob('__pycache__/*.pyc')):
        resolved = path.resolve()
        resolved.relative_to(HERE.resolve())
        if path.is_symlink() or path.parent.is_symlink():
            raise ValueError('cache_reparse')
        source = path.parent.parent / (path.name.split('.cpython-')[0] + '.py')
        if not source.is_file():
            raise ValueError('cache_without_authored_source')
        rows.append({'path': str(resolved), 'bytes': path.stat().st_size, 'sha256': sha(path),
                     'authored_source': str(source), 'source_sha256': sha(source)})
        path.unlink()
    for path in sorted(HERE.rglob('__pycache__'), reverse=True):
        path.resolve().relative_to(HERE.resolve())
        if not any(path.iterdir()):
            path.rmdir()
    save(HERE / 'CACHE_CLEANUP.json', {'scope': 'new qualification namespace generated bytecode only',
                                     'deleted': rows, 'runtime_files_deleted': 0})


