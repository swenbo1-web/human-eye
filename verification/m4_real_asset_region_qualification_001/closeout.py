def archive():
    before = [(p.relative_to(RUNTIME).as_posix(), p.stat().st_size, sha(p)) for p in inventory(RUNTIME)]
    target = HERE / 'runtime_archive'
    target.mkdir(exist_ok=False)
    entries = []
    for index, (relative, size, digest) in enumerate(before, 1):
        source = RUNTIME / relative
        copy = target / ('f' + str(index).zfill(6) + '_' + source.name[:100])
        with source.open('rb') as incoming, copy.open('xb') as outgoing:
            shutil.copyfileobj(incoming, outgoing)
            outgoing.flush()
            os.fsync(outgoing.fileno())
        assert sha(copy) == digest and copy.read_bytes() == source.read_bytes()
        entries.append({'relative': relative, 'copy': copy.relative_to(HERE).as_posix(), 'bytes': size, 'sha256': digest})
    assert before == [(p.relative_to(RUNTIME).as_posix(), p.stat().st_size, sha(p)) for p in inventory(RUNTIME)]
    save(HERE / 'RUNTIME_ARCHIVE.json', {'schema': 'real-asset-runtime-archive-v1', 'file_count': len(entries),
        'bytes': sum(row['bytes'] for row in entries), 'runtime_exclusions': [], 'originals_retained': True,
        'byte_exact': True, 'files': entries})
    print(json.dumps({'runtime_files': len(entries), 'bytes': sum(row['bytes'] for row in entries)}))


def scan(raw, name, findings):
    patterns = (rb'\b(?:sk-proj-|sk-)[A-Za-z0-9_-]{24,}', rb'\bgh[pousr]_[A-Za-z0-9]{25,}',
                rb'\bgithub_pat_[A-Za-z0-9_]{30,}', rb'\bya29\.[A-Za-z0-9_-]{25,}',
                rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----')
    if any(re.search(pattern, raw) for pattern in patterns):
        findings.append(name)
    if zipfile.is_zipfile(io.BytesIO(raw)):
        with zipfile.ZipFile(io.BytesIO(raw)) as zipped:
            for member in zipped.infolist():
                if not member.is_dir():
                    scan(zipped.read(member), name + '!' + member.filename, findings)


