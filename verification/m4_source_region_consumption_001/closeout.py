def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return json.loads(Path(path).read_bytes())


def save(path, value):
    with Path(path).open('x', encoding='utf8', newline='\n') as stream:
        json.dump(value, stream, sort_keys=True, indent=2, ensure_ascii=False, allow_nan=False)
        stream.write('\n')
        stream.flush()
        os.fsync(stream.fileno())


def inventory(directory):
    paths = []
    for current, directories, names in os.walk(directory, followlinks=False):
        for name in directories + names:
            path = Path(current) / name
            if path.is_symlink() or path.is_junction():
                raise ValueError('reparse_entry/' + str(path))
            path.resolve().relative_to(directory.resolve())
        paths.extend(Path(current) / name for name in names)
    return sorted(paths)


def clean_generated_bytecode():
    rows = []
    for path in sorted(HERE.rglob('__pycache__/*.pyc')):
        resolved = path.resolve()
        resolved.relative_to(HERE.resolve())
        if path.is_symlink() or path.parent.is_symlink():
            raise ValueError('cache_reparse')
        source = path.parent.parent / (path.name.split('.cpython-')[0] + '.py')
        if not source.is_file():
            raise ValueError('cache_without_authored_source')
        rows.append({'path': str(resolved), 'bytes': path.stat().st_size, 'sha256': sha(path),
                     'authored_source': str(source), 'source_sha256': sha(source)})
        path.unlink()
    for path in sorted(HERE.rglob('__pycache__'), reverse=True):
        path.resolve().relative_to(HERE.resolve())
        if not any(path.iterdir()):
            path.rmdir()
    save(HERE / 'CACHE_CLEANUP.json', {'scope': 'new qualification namespace generated bytecode only',
                                     'deleted': rows, 'runtime_files_deleted': 0})


def scan(raw, name, findings):
    patterns = (rb'\b(?:sk-proj-|sk-)[A-Za-z0-9_-]{24,}', rb'\bgh[pousr]_[A-Za-z0-9]{25,}',
                rb'\bgithub_pat_[A-Za-z0-9_]{30,}', rb'\bya29\.[A-Za-z0-9_-]{25,}',
                rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----')
    if any(re.search(pattern, raw) for pattern in patterns):
        findings.append(name)
    if zipfile.is_zipfile(io.BytesIO(raw)):
        with zipfile.ZipFile(io.BytesIO(raw)) as zipped:
            for member in zipped.infolist():
                if not member.is_dir():
                    scan(zipped.read(member), name + '!' + member.filename, findings)


def verify_git():
    manifest = read(HERE / 'CONTENT_MANIFEST.json')
    rows = manifest['files'] + [{'path': 'CONTENT_MANIFEST.json', 'sha256': sha(HERE / 'CONTENT_MANIFEST.json')}]
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT).decode().strip()
    prefix = HERE.relative_to(ROOT).as_posix()
    tracked = subprocess.check_output(['git', 'ls-tree', '-r', '--name-only', head, '--', prefix], cwd=ROOT).decode().splitlines()
    assert set(tracked) == {prefix + '/' + row['path'] for row in rows}
    for row in rows:
        raw = subprocess.check_output(['git', 'show', head + ':' + prefix + '/' + row['path']], cwd=ROOT)
        assert hashlib.sha256(raw).hexdigest() == row['sha256'], row['path']
    print(json.dumps({'head': head, 'exact_Git_blobs': len(rows), 'manifest_sha256': sha(HERE / 'CONTENT_MANIFEST.json')}))


def projected_event_bytes(raw):
    """Keep original public events and replace reasoning-event bodies with hashes."""
    pieces, replacements = [], []
    for line in raw.splitlines(keepends=True):
        try:
            event = json.loads(line)
        except (ValueError, UnicodeError):
            pieces.append(line)
            continue
        item = event.get('item', {})
        if item.get('type') in ('reasoning', 'analysis'):
            digest = hashlib.sha256(line).hexdigest()
            replacements.append({'original_line_sha256': digest, 'original_line_bytes': len(line),
                                 'item_id': item.get('id'), 'item_type': item.get('type')})
            replacement = {'type': event.get('type'), 'item': {'id': item.get('id'), 'type': item['type'],
                           'redacted': True}, 'original_line_sha256': digest, 'original_line_bytes': len(line)}
            pieces.append((json.dumps(replacement, sort_keys=True, separators=(',', ':')) + '\n').encode('utf8'))
        else:
            pieces.append(line)
    return b''.join(pieces), replacements


def archive():
    before = [(p.relative_to(RUNTIME).as_posix(), p.stat().st_size, sha(p)) for p in inventory(RUNTIME)]
    target = HERE / 'runtime_archive'
    target.mkdir(exist_ok=False)
    rows = []
    for index, (relative, size, digest) in enumerate(before, 1):
        source = RUNTIME / relative
        raw = source.read_bytes()
        derivation = []
        if source.name == 'stdout.raw.bin':
            shared, derivation = projected_event_bytes(raw)
        elif source.name.endswith('.raw.zip'):
            buffer = io.BytesIO()
            with zipfile.ZipFile(io.BytesIO(raw)) as original, zipfile.ZipFile(buffer, 'w') as projected:
                for info in original.infolist():
                    payload = original.read(info.filename)
                    if info.filename.endswith('stdout.raw.bin'):
                        payload, changes = projected_event_bytes(payload)
                        derivation.extend({'member': info.filename, **change} for change in changes)
                    projected.writestr(info, payload)
            shared = buffer.getvalue() if derivation else raw
        else:
            shared = raw
        copy = target / ('f' + str(index).zfill(6) + '_' + source.name[:100])
        with copy.open('xb') as stream:
            stream.write(shared)
            stream.flush()
            os.fsync(stream.fileno())
        rows.append({'relative': relative, 'copy': copy.relative_to(HERE).as_posix(),
            'original_bytes': size, 'original_sha256': digest, 'shared_bytes': len(shared),
            'sha256': sha(copy), 'byte_exact': shared == raw, 'reasoning_event_projection': derivation})
    assert before == [(p.relative_to(RUNTIME).as_posix(), p.stat().st_size, sha(p)) for p in inventory(RUNTIME)]
    save(HERE / 'RUNTIME_ARCHIVE.json', {'schema': 'consumption-runtime-archive-v1', 'file_count': len(rows),
        'original_bytes': sum(row['original_bytes'] for row in rows),
        'shared_bytes': sum(row['shared_bytes'] for row in rows), 'files': rows,
        'originals_retained_locally': True, 'original_files_deleted': 0,
        'all_runtime_members_represented': True,
        'projected_members': [row['relative'] for row in rows if not row['byte_exact']],
        'projection_scope': 'Reasoning event bodies in original stdout and its legacy ZIP copies stay local. Public answers, MCP results, images, usage and other event lines retain original bytes.'})
    print(json.dumps({'runtime_files': len(rows), 'original_bytes': sum(row['original_bytes'] for row in rows),
                      'projected_members': sum(not row['byte_exact'] for row in rows)}))


