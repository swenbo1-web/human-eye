"""Deterministic geometry rasterization for inspection, using actual triangles."""

from pathlib import Path
import sys
import time

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from common import read, write, identity
import numpy as np
from PIL import Image, ImageDraw
from geometry import mesh_geometry

VIEWS = [(1, 0, 0), (0, 1, 0), (0, 0, 1)]


def panel(vertices, faces, view, size=(440, 400), colors=None, arrows=(), title="", extent=None):
    image = Image.new("RGB", size, "#f5f6f8")
    draw = ImageDraw.Draw(image)
    camera = np.array(view, dtype=float)
    camera /= np.linalg.norm(camera)
    up = np.array((0., 1., 0.)) if abs(camera[1]) < .9 else np.array((0., 0., 1.))
    right = np.cross(up, camera)
    right /= np.linalg.norm(right)
    up = np.cross(camera, right)
    basis = np.stack((right, up, camera), axis=1)
    projected = vertices @ basis
    minimum = projected[:, :2].min(axis=0)
    maximum = projected[:, :2].max(axis=0)
    center = (minimum + maximum) / 2
    scale = min((size[0] - 50) / max(maximum[0] - minimum[0], 1e-12),
                (size[1] - 75) / max(maximum[1] - minimum[1], 1e-12))
    if extent is not None:
        center, scale = extent

    def project(points):
        xy = ((points @ basis)[:, :2] - center) * scale
        return np.c_[xy[:, 0] + size[0] / 2, -xy[:, 1] + size[1] / 2 + 15]

    pixels = project(vertices)
    tri = vertices[faces]
    cross = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    norm = np.linalg.norm(cross, axis=1)
    normals = np.divide(cross, norm[:, None], out=np.zeros_like(cross), where=norm[:, None] > 0)
    shade = .35 + .65 * np.abs(normals @ (np.array((.3, .6, .74)) / np.linalg.norm((.3, .6, .74))))
    face_colors = np.tile(np.array((125, 151, 173)), (len(faces), 1)) if colors is None else colors
    rgb = np.clip(face_colors * shade[:, None], 0, 255).astype(np.uint8)
    for index in np.argsort(projected[faces, 2].mean(axis=1), kind="stable"):
        draw.polygon([tuple(point) for point in pixels[faces[index]]], fill=tuple(rgb[index]))
    for start, vector, label, color in arrows:
        ends = project(np.stack((start, start + vector)))
        draw.line([tuple(point) for point in ends], fill=color, width=3)
        x, y = ends[1]
        draw.ellipse((x - 4, y - 4, x + 4, y + 4), fill=color)
        draw.text((x + 4, y), label, fill=color)
    draw.text((12, 10), title, fill="#152536")
    return image, (center, scale)


def render_sources():
    started, cpu = time.perf_counter(), time.process_time()
    directory = HERE / "private/views/source"
    directory.mkdir(parents=True, exist_ok=True)
    results = []
    for row in read("ACQUISITION.json")["selected"]:
        with np.load(HERE / row["array_path"]) as data:
            vertices, faces = data["vertices"], data["faces"]
            geometry = mesh_geometry(**dict(data))
        largest = max(geometry["stats"]["orientation_patches"], key=lambda item: item["triangles"])
        anchor = largest["anchor_face"]
        point = vertices[faces[anchor]].mean(axis=0)
        normal = geometry["cross"][anchor]
        normal /= np.linalg.norm(normal)
        image = Image.new("RGB", (1320, 400), "white")
        for index, view in enumerate(VIEWS):
            part, _ = panel(vertices, faces, view, arrows=[(point, normal * row["bbox_diagonal"] * .12, "face " + str(anchor) + " +normal", "#d02335")],
                            title=row["id"] + " view " + str(view))
            image.paste(part, (index * 440, 0))
        path = directory / (row["id"] + ".png")
        image.save(path)
        results.append(dict(source_id=row["id"], patch=largest["patch"], anchor_face=anchor,
                            anchor_position=point.tolist(), raw_winding_normal=normal.tolist(), view=identity(path)))
    write("SOURCE_VIEWS.json", dict(cases=results, wall_s_before_write=time.perf_counter() - started,
                                   cpu_s_before_write=time.process_time() - cpu))


def main():
    # Final paired views are generated by the QA entry point after DATASET_INDEX exists.
    from qa import render_pairs
    render_pairs()


if __name__ == "__main__":
    main()
