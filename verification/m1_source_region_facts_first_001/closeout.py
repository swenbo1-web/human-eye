HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RUNTIME = Path('D:/he_m1_source_region_facts_first_001')
PRODUCT_SOURCE = 'human_eye_plugin/live_spatial_mcp.py'


def sha(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def read(path):
    return json.loads(Path(path).read_bytes())


def save(path, value):
    with Path(path).open('x', encoding='utf8', newline='\n') as stream:
        json.dump(value, stream, sort_keys=True, indent=2, ensure_ascii=False, allow_nan=False)
        stream.write('\n')
        stream.flush()
        os.fsync(stream.fileno())


def inventory(directory):
    directory = Path(directory)
    if not directory.is_dir() or directory.is_symlink() or directory.is_junction():
        raise ValueError('invalid_inventory_root/' + str(directory))
    paths = []
    for current, directories, names in os.walk(directory, followlinks=False):
        for name in directories + names:
            path = Path(current) / name
            if path.is_symlink() or path.is_junction():
                raise ValueError('reparse_entry/' + str(path))
            path.resolve().relative_to(directory.resolve())
        paths.extend(Path(current) / name for name in names)
    return sorted(paths)


def clean_generated_bytecode():
    receipt = HERE / 'CACHE_CLEANUP.json'
    paths = [path for path in inventory(HERE) if path.suffix == '.pyc']
    if receipt.exists():
        if paths:
            raise ValueError('cleanup_receipt_already_exists_with_new_bytecode')
        print(json.dumps({'cleanup_receipt_sha256': sha(receipt), 'remaining_pyc': 0}))
        return
    rows = []
    for path in paths:
        if path.parent.name != '__pycache__':
            raise ValueError('bytecode_outside_authored_cache/' + str(path))
        source = path.parent.parent / (path.name.split('.cpython-')[0] + '.py')
        source.resolve().relative_to(HERE.resolve())
        if not source.is_file():
            raise ValueError('cache_without_authored_source/' + str(path))
        rows.append({'path': str(path.resolve()), 'bytes': path.stat().st_size,
                     'sha256': sha(path), 'authored_source': str(source),
                     'source_sha256': sha(source)})
    for row in rows:
        path = Path(row['path'])
        if path.stat().st_size != row['bytes'] or sha(path) != row['sha256']:
            raise ValueError('cache_changed_before_cleanup/' + str(path))
        path.unlink()
    for path in sorted(HERE.rglob('__pycache__'), reverse=True):
        path.resolve().relative_to(HERE.resolve())
        if not any(path.iterdir()):
            path.rmdir()
    save(receipt, {'scope': 'new qualification namespace generated bytecode only',
                   'deleted': rows, 'runtime_files_deleted': 0})
    print(json.dumps({'deleted_generated_pyc': len(rows), 'runtime_files_deleted': 0}))


def scan(raw, name, findings):
    patterns = (rb'\b(?:sk-proj-|sk-)[A-Za-z0-9_-]{24,}',
                rb'\bgh[pousr]_[A-Za-z0-9]{25,}',
                rb'\bgithub_pat_[A-Za-z0-9_]{30,}',
                rb'\bya29\.[A-Za-z0-9_-]{25,}',
                rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----')
    if any(re.search(pattern, raw) for pattern in patterns):
        findings.append(name)
    if zipfile.is_zipfile(io.BytesIO(raw)):
        with zipfile.ZipFile(io.BytesIO(raw)) as zipped:
            for member in zipped.infolist():
                if not member.is_dir():
                    scan(zipped.read(member), name + '!' + member.filename, findings)


def changed_paths(baseline_git):
    changed = subprocess.check_output(
        ['git', 'diff', '--name-only', '--no-renames', '-z', baseline_git, '--'], cwd=ROOT)
    untracked = subprocess.check_output(
        ['git', 'ls-files', '--others', '--exclude-standard', '-z'], cwd=ROOT)
    paths = sorted(set((changed + untracked).decode('utf8').split('\0')) - {''})
    prefix = HERE.relative_to(ROOT).as_posix() + '/'
    unexpected = [path for path in paths
                  if path != PRODUCT_SOURCE and not path.startswith(prefix)]
    if unexpected:
        raise ValueError('source_changes_outside_allowed_scope/' + json.dumps(unexpected))
    return paths


def verify_git():
    manifest_path = HERE / 'CONTENT_MANIFEST.json'
    manifest = read(manifest_path)
    rows = manifest['files'] + [{'path': 'CONTENT_MANIFEST.json',
                               'bytes': manifest_path.stat().st_size,
                               'sha256': sha(manifest_path)}]
    expected = {row['path'] for row in rows}
    if len(expected) != len(rows):
        raise ValueError('duplicate_manifest_path')
    if {path.relative_to(HERE).as_posix() for path in inventory(HERE)} != expected:
        raise ValueError('worktree_namespace_members_differ_from_manifest')
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT).decode().strip()
    prefix = HERE.relative_to(ROOT).as_posix()
    tracked = subprocess.check_output(
        ['git', 'ls-tree', '-r', '--name-only', '-z', head, '--', prefix], cwd=ROOT)
    if set(tracked.decode('utf8').split('\0')) - {''} != {
            prefix + '/' + row['path'] for row in rows}:
        raise ValueError('Git_namespace_members_differ_from_manifest')
    for row in rows:
        path = HERE / row['path']
        path.resolve().relative_to(HERE.resolve())
        raw = subprocess.check_output(
            ['git', 'show', head + ':' + prefix + '/' + row['path']], cwd=ROOT)
        if (len(raw) != row['bytes'] or hashlib.sha256(raw).hexdigest() != row['sha256']
                or path.stat().st_size != row['bytes'] or sha(path) != row['sha256']):
            raise ValueError('Git_or_worktree_blob_identity_mismatch/' + row['path'])
    changed_paths(read(HERE / 'BASELINE.json')['baseline_git'])
    print(json.dumps({'head': head, 'exact_Git_blobs': len(rows),
                      'manifest_sha256': sha(manifest_path)}))


def projected_event_bytes(raw):
    """Project reasoning/analysis event lines to original-line size and SHA-256."""
    pieces, replacements = [], []
    for line_number, line in enumerate(raw.splitlines(keepends=True), 1):
        try:
            event = json.loads(line)
        except (ValueError, UnicodeError):
            pieces.append(line)
            continue
        if not isinstance(event, dict):
            pieces.append(line)
            continue
        item = event.get('item')
        item = item if isinstance(item, dict) else {}
        kind = item.get('type')
        if kind not in ('reasoning', 'analysis'):
            kind = event.get('type')
        if kind not in ('reasoning', 'analysis'):
            pieces.append(line)
            continue
        digest = hashlib.sha256(line).hexdigest()
        identity = {'original_line_number': line_number, 'original_line_sha256': digest,
                    'original_line_bytes': len(line), 'item_type': kind}
        if isinstance(item.get('id'), str):
            identity['item_id'] = item['id']
        replacements.append(identity)
        replacement = {'redacted': True, **identity}
        if isinstance(event.get('type'), str):
            replacement['type'] = event['type']
        pieces.append((json.dumps(replacement, sort_keys=True, separators=(',', ':'))
                       + '\n').encode('utf8'))
    return b''.join(pieces), replacements


def projected_zip_bytes(raw):
    buffer = io.BytesIO()
    derivation, members = [], []
    with zipfile.ZipFile(io.BytesIO(raw)) as original, zipfile.ZipFile(buffer, 'w') as projected:
        projected.comment = original.comment
        for index, info in enumerate(original.infolist()):
            payload = original.read(info)
            shared, changes = shared_runtime_bytes(info.filename, payload)
            derivation.extend({'member_index': index, 'member': info.filename, **change}
                              for change in changes)
            members.append({'index': index, 'name': info.filename,
                            'original_bytes': len(payload),
                            'original_sha256': hashlib.sha256(payload).hexdigest(),
                            'shared_bytes': len(shared),
                            'sha256': hashlib.sha256(shared).hexdigest(),
                            'byte_exact': shared == payload})
            projected.writestr(copy.copy(info), shared)
    return (buffer.getvalue() if derivation else raw), derivation, members


def shared_runtime_bytes(name, raw):
    normalized = name.replace('\\', '/')
    if normalized.rsplit('/', 1)[-1] == 'stdout.raw.bin':
        return projected_event_bytes(raw)
    if normalized.endswith('.raw.zip'):
        shared, derivation, _ = projected_zip_bytes(raw)
        return shared, derivation
    return raw, []


def archive():
    manifest_path = HERE / 'RUNTIME_ARCHIVE.json'
    if manifest_path.exists():
        archive_manifest = verify_archive()
        print(json.dumps({'runtime_files': archive_manifest['file_count'],
                          'original_bytes': archive_manifest['original_bytes'],
                          'archive_reverified': True}))
        return
    before = [(path.relative_to(RUNTIME).as_posix(), path.stat().st_size, sha(path))
              for path in inventory(RUNTIME)]
    target = HERE / 'runtime_archive'
    target.mkdir(exist_ok=True)
    inventory(target)
    rows = []
    for index, (relative, size, digest) in enumerate(before, 1):
        source = RUNTIME / relative
        raw = source.read_bytes()
        if len(raw) != size or hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError('runtime_changed_during_archive/' + relative)
        members = []
        if source.name.endswith('.raw.zip'):
            shared, derivation, members = projected_zip_bytes(raw)
        else:
            shared, derivation = shared_runtime_bytes(relative, raw)
        copy_path = target / ('f' + str(index).zfill(6) + '_' + source.name[:100])
        shared_digest = hashlib.sha256(shared).hexdigest()
        if copy_path.exists():
            if copy_path.stat().st_size != len(shared) or sha(copy_path) != shared_digest:
                raise ValueError('existing_archive_copy_mismatch/' + copy_path.name)
        else:
            partial = copy_path.with_name(copy_path.name + '.partial')
            with partial.open('wb') as stream:
                stream.write(shared)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(partial, copy_path)
        rows.append({'relative': relative, 'original_path': str(source),
                     'copy': copy_path.relative_to(HERE).as_posix(),
                     'original_bytes': size, 'original_sha256': digest,
                     'shared_bytes': len(shared), 'sha256': shared_digest,
                     'byte_exact': shared == raw, 'reasoning_event_projection': derivation,
                     'zip_members': members})
    after = [(path.relative_to(RUNTIME).as_posix(), path.stat().st_size, sha(path))
             for path in inventory(RUNTIME)]
    if before != after:
        raise ValueError('runtime_inventory_changed_during_archive')
    if {path.relative_to(HERE).as_posix() for path in inventory(target)} != {
            row['copy'] for row in rows}:
        raise ValueError('unexpected_archive_copy')
    save(manifest_path, {'schema': 'facts-first-runtime-archive-v1',
        'runtime_root': str(RUNTIME), 'file_count': len(rows),
        'original_bytes': sum(row['original_bytes'] for row in rows),
        'shared_bytes': sum(row['shared_bytes'] for row in rows), 'files': rows,
        'originals_retained_locally': True, 'original_files_deleted': 0,
        'all_runtime_members_represented': True,
        'projected_members': [row['relative'] for row in rows if not row['byte_exact']],
        'projection_scope': 'Reasoning and analysis event bodies in stdout.raw.bin and '
            'raw ZIP members are represented by original-line SHA-256 and byte count. '
            'Other event lines, files and ZIP member payloads retain their original bytes. '
            'ZIP containers with projected members are repacked. All originals stay local.'})
    print(json.dumps({'runtime_files': len(rows),
                      'original_bytes': sum(row['original_bytes'] for row in rows),
                      'shared_bytes': sum(row['shared_bytes'] for row in rows),
                      'projected_members': sum(not row['byte_exact'] for row in rows)}))


def verify_archive():
    manifest = read(HERE / 'RUNTIME_ARCHIVE.json')
    rows = manifest['files']
    if manifest['runtime_root'] != str(RUNTIME) or manifest['file_count'] != len(rows):
        raise ValueError('runtime_archive_header_mismatch')
    expected = [(row['relative'], row['original_bytes'], row['original_sha256']) for row in rows]
    actual = [(path.relative_to(RUNTIME).as_posix(), path.stat().st_size, sha(path))
              for path in inventory(RUNTIME)]
    if expected != actual:
        raise ValueError('runtime_archive_original_inventory_mismatch')
    copies = {row['copy'] for row in rows}
    if len(copies) != len(rows) or copies != {
            path.relative_to(HERE).as_posix() for path in inventory(HERE / 'runtime_archive')}:
        raise ValueError('runtime_archive_copy_inventory_mismatch')
    for row in rows:
        source = RUNTIME / row['relative']
        copy_path = HERE / row['copy']
        source.resolve().relative_to(RUNTIME.resolve())
        copy_path.resolve().relative_to((HERE / 'runtime_archive').resolve())
        raw = source.read_bytes()
        members = []
        if source.name.endswith('.raw.zip'):
            shared, derivation, members = projected_zip_bytes(raw)
        else:
            shared, derivation = shared_runtime_bytes(row['relative'], raw)
        if (len(shared) != row['shared_bytes']
                or hashlib.sha256(shared).hexdigest() != row['sha256']
                or copy_path.read_bytes() != shared
                or row['byte_exact'] != (shared == raw)
                or row['reasoning_event_projection'] != derivation
                or row['zip_members'] != members):
            raise ValueError('runtime_archive_projection_identity_mismatch/' + row['relative'])
    if (manifest['original_bytes'] != sum(row['original_bytes'] for row in rows)
            or manifest['shared_bytes'] != sum(row['shared_bytes'] for row in rows)
            or not manifest['originals_retained_locally']
            or manifest['original_files_deleted'] != 0
            or not manifest['all_runtime_members_represented']):
        raise ValueError('runtime_archive_totals_mismatch')
    return manifest


def seal():
    started = time.perf_counter_ns()
    if (HERE / 'FINAL_AUDIT.json').exists() or (HERE / 'CONTENT_MANIFEST.json').exists():
        raise ValueError('seal_output_already_exists')
    baseline = read(HERE / 'BASELINE.json')
    frozen = read(HERE / 'FROZEN.json')
    for name, rows in (('baseline_direct_pins', baseline['direct_pins']),
                       ('frozen_direct_inputs', frozen['direct_inputs'])):
        if not rows:
            raise ValueError('empty_' + name)
        for row in rows:
            path = Path(row['path'])
            if sha(path) != row['sha256'] or (
                    'bytes' in row and path.stat().st_size != row['bytes']):
                raise ValueError(name + '_identity_mismatch/' + str(path))
    changes = changed_paths(baseline['baseline_git'])
    pyc = [path for path in inventory(HERE) if path.suffix.lower() == '.pyc']
    if pyc:
        raise ValueError('namespace_contains_pyc/' + json.dumps([str(path) for path in pyc]))
    archive_manifest = verify_archive()
    decision_path = HERE / 'DECISION.json'
    decision = read(decision_path)
    summary = decision.get('summary', {})
    summary = summary if isinstance(summary, dict) else {}
    decision_name = decision.get('decision')
    accepted = decision.get('accepted_cases', summary.get('accepted_cases'))
    denominator = decision.get('case_denominator', summary.get('case_denominator'))
    if not isinstance(decision_name, str) or not decision_name:
        raise ValueError('decision_name_missing')
    if type(accepted) is not int or accepted < 0:
        raise ValueError('accepted_cases_missing_or_invalid')
    if denominator is not None and (type(denominator) is not int or denominator < accepted):
        raise ValueError('case_denominator_invalid')
    runtime_review = HERE / 'checks/FINAL_RUNTIME_REVIEW.json'
    runtime_review_identity = {'path': runtime_review.relative_to(HERE).as_posix(),
                               'bytes': runtime_review.stat().st_size,
                               'sha256': sha(runtime_review)}
    findings = []
    for path in inventory(HERE):
        scan(path.read_bytes(), path.relative_to(HERE).as_posix(), findings)
    if findings:
        raise ValueError('credential_like_bytes_require_local_review/' + json.dumps(findings))
    audit_completed = time.perf_counter_ns()
    closeout_started = read(HERE / 'CLOSEOUT_STARTED.json')['started_ns']
    preparation_started = read(HERE / 'PREPARATION_STARTED.json')['started_ns']
    save(HERE / 'FINAL_AUDIT.json', {
        'schema': 'facts-first-final-audit-v1', 'task': baseline.get('task'),
        'baseline_git': baseline['baseline_git'],
        'baseline_direct_pins_verified': True,
        'baseline_direct_pin_count': len(baseline['direct_pins']),
        'current_execution_freeze_verified': True,
        'frozen_direct_input_count': len(frozen['direct_inputs']),
        'baseline_sha256': sha(HERE / 'BASELINE.json'),
        'frozen_sha256': sha(HERE / 'FROZEN.json'),
        'allowed_product_source': PRODUCT_SOURCE,
        'allowed_namespace': HERE.relative_to(ROOT).as_posix(),
        'changed_paths': changes, 'product_changes': int(PRODUCT_SOURCE in changes),
        'current_product_source_sha256': sha(ROOT / PRODUCT_SOURCE),
        'namespace_pyc_count': 0, 'credential_scan': 'passed', 'credential_findings': 0,
        'original_runtime_files_deleted': 0, 'runtime_archive_verified': True,
        'runtime_file_count': archive_manifest['file_count'],
        'runtime_original_bytes': archive_manifest['original_bytes'],
        'runtime_shared_bytes': archive_manifest['shared_bytes'],
        'runtime_archive_sha256': sha(HERE / 'RUNTIME_ARCHIVE.json'),
        'shared_archive_reasoning_projection': True,
        'decision': decision_name, 'accepted_cases': accepted, 'case_denominator': denominator,
        'decision_identity': {'path': 'DECISION.json', 'bytes': decision_path.stat().st_size,
                              'sha256': sha(decision_path)},
        'timing': {'seal_started_ns': started, 'audit_completed_ns': audit_completed,
            'seal_audit_seconds': (audit_completed - started) / 1e9,
            'closeout_envelope_seconds': (audit_completed - closeout_started) / 1e9,
            'preparation_through_final_audit_seconds': (audit_completed - preparation_started) / 1e9,
            'scope': 'Recorded preparation through final audit. The final manifest write, Git verification/publication and administrator review continue after this boundary.'},
        'final_runtime_review_identity': runtime_review_identity,
        'runtime_review_scope': 'The final runtime review is bound by its complete file identity. '
            'Its own recorded checks and pass criteria govern the review result.'})
    rows = [{'path': path.relative_to(HERE).as_posix(), 'bytes': path.stat().st_size,
             'sha256': sha(path)} for path in inventory(HERE)]
    save(HERE / 'CONTENT_MANIFEST.json', {'schema': 'facts-first-content-manifest-v1',
        'self_excluded': 'CONTENT_MANIFEST.json', 'file_count_excluding_self': len(rows),
        'files': rows})
    print(json.dumps({'manifest_members': len(rows),
                      'sha256': sha(HERE / 'CONTENT_MANIFEST.json'),
                      'decision': decision_name, 'accepted_cases': accepted,
                      'case_denominator': denominator}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('cleanup', 'archive', 'seal', 'verify-git'))
    args = parser.parse_args()
    {'cleanup': clean_generated_bytecode, 'archive': archive,
     'seal': seal, 'verify-git': verify_git}[args.action]()
