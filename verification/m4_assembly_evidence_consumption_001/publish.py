"""Seal the local raw runtime and enumerate evidence safe to publish in Git."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time
import zipfile


NS = Path(__file__).resolve().parent
sys.path.insert(0, str(NS / 'harness'))
from common import ASSET, ASSET_SHA256, BASELINE, EXTERNAL, ROOT, read, save, sha


def raw_paths():
    paths = []
    for part in ('slots', 'budget', 'preflight'):
        root = EXTERNAL / part
        for path in root.rglob('*'):
            if path.is_symlink() or path.is_junction() or not path.resolve().is_relative_to(root.resolve()):
                raise ValueError('unexpected reparse point in runtime evidence')
            if path.is_file():
                paths.append(path)
    return sorted(paths)


def archive():
    started = time.perf_counter_ns()
    for label in ('A1', 'B1'):
        publication = EXTERNAL / 'slots' / label / 'SLOT_PUBLICATION.json'
        if sha(publication.with_name('SLOT_RESULT.json')) != read(publication)['result_sha256']:
            raise ValueError('original slot publication is missing or changed')
    paths = raw_paths()
    rows = [{'path': p.relative_to(EXTERNAL).as_posix(), 'bytes': p.stat().st_size, 'sha256': sha(p)} for p in paths]
    output = EXTERNAL / 'ORIGINAL_RUNTIME.zip'
    with zipfile.ZipFile(output, 'x', compression=zipfile.ZIP_DEFLATED, compresslevel=4) as bundle:
        for p, row in zip(paths, rows, strict=True):
            bundle.write(p, row['path'])
    with zipfile.ZipFile(output) as bundle:
        if bundle.namelist() != [row['path'] for row in rows]:
            raise ValueError('runtime archive members changed')
        for p, row in zip(paths, rows, strict=True):
            with bundle.open(row['path']) as stream:
                actual = hashlib.file_digest(stream, 'sha256').hexdigest()
            if actual != row['sha256'] or sha(p) != actual or p.stat().st_size != row['bytes']:
                raise ValueError('runtime archive or original bytes changed: ' + row['path'])
    if paths != raw_paths():
        raise ValueError('runtime inventory changed during archive')
    index = {'started_ns': started, 'closed_ns': time.perf_counter_ns(), 'file_count': len(rows),
             'original_bytes': sum(row['bytes'] for row in rows), 'files': rows,
             'archive': {'path': str(output), 'bytes': output.stat().st_size, 'sha256': sha(output)},
             'publication_scope': 'Raw process event streams remain in the local archive. Git holds byte identities, '
                                  'the public answers and first packets, and validation receipts.'}
    save(NS / 'RUNTIME_INDEX.json', index)
    print(index['file_count'], index['archive'])


def finalize():
    result = subprocess.check_output(['git', 'diff', '--name-only', BASELINE], cwd=ROOT).decode().splitlines()
    if sha(ASSET) != ASSET_SHA256 or any(not f.startswith(NS.relative_to(ROOT).as_posix() + '/') for f in result):
        raise ValueError('product, original assembly, or another line changed')
    frozen = NS / 'FROZEN.json'
    for row in read(frozen)['direct_inputs']:
        f = Path(row['path'])
        if sha(f) != row['sha256'] or f.stat().st_size != row['bytes']:
            raise ValueError('frozen input changed: ' + str(f))
    artifact = read(NS / 'RUNTIME_INDEX.json')['archive']
    if sha(artifact['path']) != artifact['sha256']:
        raise ValueError('original archive changed')
    required = ['ANSWERS_SEALED.json', 'FIRST_PACKETS_SEALED.json', 'RUNTIME_INDEX.json',
                'scoring/EVIDENCE_VERDICT.json', 'scoring/QUALITY.json', 'checks/RUNTIME_REVIEW.json',
                'checks/EVIDENCE_INCREMENT.json', 'REPORT.md']
    artifact_pins = {f: sha(NS / f) for f in required}
    results = read(NS / 'checks/RUNTIME_REVIEW.json')['slots']
    save(NS / 'DECISION.json', {'task': 'M4-ASSEMBLY-EVIDENCE-CONSUMPTION-001',
         'fixed_denominator': 2, 'launch_order': ['A1', 'B1'], 'replacement_consumers': 0,
         'original_asset_sha256': ASSET_SHA256, 'freeze_sha256': sha(frozen), 'artifact_sha256': artifact_pins,
         'slots': [{k: row.get(k) for k in ('slot', 'status', 'full_window_s', 'startup_to_answer_s',
                                          'owner_text_UTF8_bytes')} for row in results],
         'agent_learning_registration': read(NS / 'PREPARED.json')['agent_learning_registration'],
         'other_product_or_deployment_changes': 0})
    manifest = NS / 'CONTENT_MANIFEST.json'
    files = [f for f in sorted(NS.rglob('*')) if f.is_file() and f != manifest]
    if any(f.suffix == '.pyc' for f in files):
        raise ValueError('generated bytecode unexpectedly entered recorded evidence')
    rows = [{'path': f.relative_to(NS).as_posix(), 'bytes': f.stat().st_size, 'sha256': sha(f)} for f in files]
    save(manifest, {'files': rows, 'count': len(rows), 'self_excluded': True})
    print(len(rows) + 1, sha(manifest))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('archive', 'finalize'))
    globals()[parser.parse_args().action]()
