"""Blender-side JSON worker; launched by BlenderProcessHost, never saves files.

Import the host by its source path so Blender does not need the engine's NumPy
and Pillow dependencies installed in its private Python runtime.
"""
from __future__ import annotations

import importlib.util
import hashlib
import json
import os
from pathlib import Path
import sys
import time
from typing import Any


RPC_PREFIX = "HUMAN_EYE_RPC:"
PROTOCOL_VERSION = "1.0"
COMMON_NATIVE_PROTOCOL = 'owned-common-native-v1-20261031'
READONLY_EVIDENCE_PROTOCOL = 'owned-readonly-native-evidence-v1-20261031'
RENDER_AUDIT_PROTOCOL = 'owned-native-render-audit-v1-20261031'
MULTISCALE_PROTOCOL = 'owned-native-multiscale-v1-20261031'
NATIVE_OBSERVATION_PROTOCOL = 'typed-native-readonly-observation-v1-20261031'


def _reject_constant(value: str) -> None:
    raise ValueError(f"non-finite JSON number: {value}")


def _emit(envelope: dict[str, Any]) -> None:
    serialized = json.dumps(envelope, ensure_ascii=True, allow_nan=False, separators=(",", ":"))
    sys.stdout.write(RPC_PREFIX + serialized + "\n")
    sys.stdout.flush()


def run_worker(root: Path) -> None:
    # The fixed child imports source directly; keep generated bytecode outside
    # the release contract by disabling writes before any engine import.
    sys.dont_write_bytecode = True
    import bpy

    source = root / "human_eye_plugin" / "blender_host.py"
    spec = importlib.util.spec_from_file_location("human_eye_blender_host_worker", source)
    if spec is None or spec.loader is None:
        raise RuntimeError("Cannot load Blender scene host")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    # Execute this snapshot rather than letting the loader accept a stale pyc.
    # Read-only capabilities bind their host digest to these actual bytes.
    with source.open('rb') as stream:host_source_bytes=stream.read(512*1024+1)
    if len(host_source_bytes)>512*1024:
        raise RuntimeError('Blender scene host source exceeds its fixed bound')
    exec(compile(host_source_bytes,str(source),'exec',dont_inherit=True),module.__dict__)
    module._READONLY_LOADED_HOST_SHA256=hashlib.sha256(host_source_bytes).hexdigest()
    host_options = {'execution_metadata': True}
    if getattr(module.BlenderSceneHost, 'identity_metadata_protocol', None) == 'host-identity-v1-20261026':
        host_options['identity_metadata'] = True
    host = module.BlenderSceneHost(**host_options)
    deadline_protocol = deadline_clock = None
    deadline_source = root/'human_eye_plugin'/'forward_deadline.py'
    if (deadline_source.is_file() and callable(getattr(host, 'require_forward_deadline', None))
            and callable(getattr(host, 'bind_forward_deadline', None))
            and callable(getattr(host, '_readonly_clock_module', None))):
        deadline_module = host._readonly_clock_module()
        if getattr(host, 'forward_deadline_protocol', None) == deadline_module.PROTOCOL:
            try:
                deadline_clock = deadline_module.counter_descriptor()
                deadline_protocol = deadline_module.PROTOCOL
            except ValueError:
                pass  # Unsupported runtimes retain only the legacy capability.

    def motion_report(value):
        # This worker has one typed stdin command path, no UI and no generic
        # code execution. The enclosing ProcessHost separately verifies the
        # fixed worker path and handshake; shared MCP hosts cannot use this.
        report = json.loads(json.dumps(value, allow_nan=False))
        report['coverage'] = {'protocol':'owned-typed-worker-meter-v1-20261030',
            'scope':'all_legal_setters_of_this_owned_typed_worker',
            'process_id':os.getpid(), 'generic_code_execution':False,
            'ui_attached':False, 'external_process_or_modified_worker_proof':False}
        complete = (report['registered_events_complete'] is True
                    and report['unknown_event_count'] == 0 and not report['closed']
                    and report['frozen_reason'] is None)
        report['registered_source_scope'] = report['scope']
        report['scope'] = 'all_legal_setters_of_this_owned_typed_worker'
        report['all_channels_complete'] = complete
        report['goal_budget_eligible'] = complete
        report['physical_meter']['complete'] = complete
        return report

    def episode_report(value):
        report=json.loads(json.dumps(value,allow_nan=False))
        report['coverage']={'protocol':COMMON_NATIVE_PROTOCOL,
            'scope':'all_legal_setters_of_this_owned_typed_worker','process_id':os.getpid(),
            'generic_code_execution':False,'ui_attached':False,
            'external_process_or_modified_worker_proof':False}
        return report
    for line in sys.stdin:
        request_id = None
        command = None
        try:
            request = json.loads(line, parse_constant=_reject_constant)
            if not isinstance(request, dict):
                raise ValueError("request must be an object")
            request_id = request.get("id")
            if isinstance(request_id, bool) or not isinstance(request_id, int):
                raise ValueError("request id must be an integer")
            command = request.get("command")
            params = request.get("params", {})
            if not isinstance(params, dict):
                raise ValueError("params must be an object")
            if command == "capabilities":
                result = {"protocol_version": PROTOCOL_VERSION, "blender_version": bpy.app.version_string,
                          "connection": "owned_headless_process", "persistent": True,
                          "saves_original_file": False, "attaches_to_open_window": False,
                          'motion_meter_protocol':'owned-typed-worker-meter-v1-20261030',
                          'generic_code_execution':False, 'process_id':os.getpid(),
                          'host_monotonic_clock':vars(time.get_clock_info('monotonic')),
                          'forward_deadline_protocol':deadline_protocol,
                          'forward_deadline_clock':deadline_clock,
                          'common_native_protocol': COMMON_NATIVE_PROTOCOL if all(callable(getattr(host, name, None))
                              for name in ('begin_owned_episode','owned_episode_status','native_scene_query','native_look','native_transform')) else None,
                          'common_native_clock':deadline_clock,
                          'readonly_native_evidence_protocol': READONLY_EVIDENCE_PROTOCOL
                              if (getattr(host, 'readonly_native_evidence_protocol', None) == READONLY_EVIDENCE_PROTOCOL
                                  and callable(getattr(host, 'capture_readonly_evidence', None))) else None,
                          'native_render_audit_protocol': RENDER_AUDIT_PROTOCOL
                              if (getattr(host, 'native_render_audit_protocol', None) == RENDER_AUDIT_PROTOCOL
                                  and all(callable(getattr(host, name, None))
                                      for name in ('native_render_state','last_native_render_audit'))) else None,
                          'native_multiscale_protocol':MULTISCALE_PROTOCOL
                              if (getattr(host, 'native_multiscale_protocol', None) == MULTISCALE_PROTOCOL
                                  and all(callable(getattr(host, name, None))
                                      for name in ('native_look_multiscale','last_native_multiscale_audit'))) else None,
                          'native_observation_capabilities':host.native_observation_capabilities()
                              if (getattr(host,'native_observation_protocol',None)==NATIVE_OBSERVATION_PROTOCOL
                                  and all(callable(getattr(host,name,None)) for name in
                                      ('native_observation_capabilities','observe_readonly_native','last_readonly_native_audit'))) else None}
            elif command == "capture":
                result = host.capture_scene()
            elif command in ('patch_observation_capabilities','observe_patch'):
                required=set() if command=='patch_observation_capabilities' else {'request_id','object_id','patch','deadline_ns'}
                if set(params)!=required:raise ValueError('Invalid typed patch observation arguments')
                result=getattr(host,command)(**params)
            elif command == 'mesh_structure_capabilities':
                if params:raise ValueError('Raw mesh capabilities accepts no arguments')
                result=host.mesh_structure_capabilities()
            elif command == 'observe_mesh_structure':
                if set(params)!={'request_id','object_id','categories','deadline_ns'}:
                    raise ValueError('Invalid typed raw mesh observation arguments')
                result=host.observe_mesh_structure(**params)
            elif command in ('native_observation_capabilities','observe_readonly_native','last_readonly_native_audit'):
                if getattr(host,'native_observation_protocol',None)!=NATIVE_OBSERVATION_PROTOCOL:
                    raise ValueError('Typed readonly native observation is unavailable')
                required={'native_observation_capabilities':set(),
                    'observe_readonly_native':{'request_id','focal_id','reference_id','expected_capture_revision','deadline_ns','view'},
                    'last_readonly_native_audit':{'request_id'}}[command]
                if set(params)!=required:raise ValueError('Invalid typed readonly observation arguments')
                result=getattr(host,command)(**params)
            elif command == 'capture_evidence':
                if params:raise ValueError('capture_evidence accepts no arguments')
                result = host.capture_evidence()
            elif command == 'capture_readonly_evidence':
                if params:raise ValueError('capture_readonly_evidence accepts no arguments')
                if (getattr(host, 'readonly_native_evidence_protocol', None) != READONLY_EVIDENCE_PROTOCOL
                        or not callable(getattr(host, 'capture_readonly_evidence', None))):
                    raise ValueError('Readonly native evidence is unavailable')
                result = host.capture_readonly_evidence()
            elif command in ('native_render_state', 'last_native_render_audit'):
                if params:raise ValueError(command + ' accepts no arguments')
                if (getattr(host, 'native_render_audit_protocol', None) != RENDER_AUDIT_PROTOCOL
                        or not callable(getattr(host, command, None))):
                    raise ValueError('Owner render audit is unavailable')
                result = getattr(host, command)()
            elif command == 'motion_begin':
                if set(params) != {'goal_id','focal_id','reference_id','limits'}:
                    raise ValueError('Invalid motion_begin arguments')
                result = motion_report(host.begin_motion_goal(**params))
            elif command == 'motion_status':
                if set(params) != {'goal_id','after_event_count'}:
                    raise ValueError('Invalid motion_status arguments')
                result = motion_report(host.motion_goal_status(**params))
            elif command == 'motion_end':
                if set(params) != {'goal_id'}:raise ValueError('Invalid motion_end arguments')
                result = motion_report(host.end_motion_goal(**params))
            elif command == 'deadline_require':
                if deadline_protocol is None or set(params) != {'goal_id'}:
                    raise ValueError('Deadline requirement capability or arguments unavailable')
                result = host.require_forward_deadline(**params)
            elif command == 'deadline_bind':
                if deadline_protocol is None or set(params) != {'lease'}:
                    raise ValueError('Deadline lease capability or arguments unavailable')
                result = host.bind_forward_deadline(**params)
            elif command == 'episode_begin':
                if set(params) != {'episode_id','focal_id','reference_id','deadline_ns','read_only','limits'}:
                    raise ValueError('Invalid episode_begin arguments')
                result = episode_report(host.begin_owned_episode(**params))
            elif command == 'episode_status':
                if set(params) != {'after_event_count'}:
                    raise ValueError('Invalid episode_status arguments')
                result = episode_report(host.owned_episode_status(**params))
            elif command == 'native_scene_query':
                if params:raise ValueError('native_scene_query accepts no arguments')
                result = host.native_scene_query()
            elif command == 'native_look':
                if set(params) != {'view'}:raise ValueError('Invalid native_look arguments')
                result = host.native_look(**params)
            elif command in ('native_look_multiscale','last_native_multiscale_audit'):
                expected = {'view'} if command=='native_look_multiscale' else set()
                if set(params) != expected:raise ValueError('Invalid '+command+' arguments')
                if (getattr(host, 'native_multiscale_protocol', None) != MULTISCALE_PROTOCOL
                        or not callable(getattr(host, command, None))):
                    raise ValueError('Native multiscale observation is unavailable')
                result = getattr(host, command)(**params)
            elif command == 'native_transform':
                if set(params) != {'object_id','delta_world_m','expected_revision'}:
                    raise ValueError('Invalid native_transform arguments')
                result = host.native_transform(**params)
            elif command == "apply":
                arguments = {"action": params.get("action"), "expected_revision": params.get("expected_revision"),
                             "expected_fingerprint": params.get("expected_fingerprint")}
                # Omission preserves the legacy host signature. An explicit
                # nonce belongs to this invocation and must reach the helper.
                if "request_nonce" in params:
                    arguments["request_nonce"] = params["request_nonce"]
                if 'forward_deadline' in params:
                    if (deadline_protocol is None or set(params) -
                            {'action','expected_revision','expected_fingerprint','request_nonce','forward_deadline'}):
                        raise ValueError('Unnegotiated or malformed forward deadline request')
                    arguments['forward_deadline'] = params['forward_deadline']
                result = host.apply_transform(**arguments)
            elif command == "shutdown":
                _emit({"id": request_id, "result": {"closed": True}})
                break
            else:
                raise ValueError("unsupported worker command")
            _emit({"id": request_id, "result": result})
        except Exception as exc:
            # A transform exception may follow a partial host mutation. Discard
            # this connection rather than authorizing another operation on it.
            known_episode_refusal = (command == 'native_transform'
                and isinstance(exc, getattr(module, 'EpisodePrewriteRefused', ())))
            uncertain = (command == 'apply' or command == 'native_transform' and not known_episode_refusal
                or isinstance(exc, getattr(module, 'EpisodeUncertain', ())))
            _emit({"id": request_id, "error": {"type": type(exc).__name__, "message": str(exc)[:2000],
                                                 "mutation_uncertain": uncertain,
                                                 **({'known_preentry_refusal': True, 'executed': False}
                                                    if known_episode_refusal else {})}})
            if uncertain:
                break


if __name__ == "__main__":
    arguments = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    if len(arguments) != 1:
        raise SystemExit("Expected the project root after Blender's -- argument")
    run_worker(Path(arguments[0]).resolve())
